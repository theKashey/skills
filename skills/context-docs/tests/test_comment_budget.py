"""Behavioral tests for scripts/comment_budget.py.

Run from the skill directory: python3 -m unittest discover tests
"""

import contextlib
import importlib.util
import io
import json
import os
import pathlib
import tempfile
import unittest

SCRIPT = pathlib.Path(__file__).resolve().parents[1] / "scripts" / "comment_budget.py"
spec = importlib.util.spec_from_file_location("comment_budget", SCRIPT)
cb = importlib.util.module_from_spec(spec)
spec.loader.exec_module(cb)


def lines(n, prefix=" * "):
    return "\n".join(f"{prefix}fact {i} the reader needs" for i in range(n))


def overview(n):
    return f"/**\n{lines(n)}\n */\nimport x from 'x';\n\nexport const a = 1;\n"


class Classification(unittest.TestCase):
    def kinds(self, src, name="f.ts"):
        return {(s["kind"], s["lines"]) for s in cb.surfaces(name, src)}

    def test_overview_is_first_comment_before_code(self):
        self.assertEqual(self.kinds(overview(16)), {("overview", 16)})

    def test_overview_after_imports_still_counts(self):
        src = "import a from 'a';\n\n/**\n" + lines(16) + "\n */\n\nexport const a = 1;\n"
        self.assertEqual(self.kinds(src), {("overview", 16)})

    def test_docblock_on_declaration_is_jsdoc(self):
        src = "const x = 1;\n/**\n" + lines(11) + "\n */\nexport function f() {}\n"
        self.assertEqual(self.kinds(src), {("jsdoc", 11)})

    def test_two_line_run_is_a_block_and_one_line_has_no_budget(self):
        src = "const a = 1;\n// one\n// two\nconst b = 2; // trailing\n// alone\nconst c = 3;\n"
        self.assertEqual(self.kinds(src), {("block", 2)})

    def test_bare_tags_blank_and_delimiters_do_not_count(self):
        src = (
            "const x = 1;\n/**\n * Purpose line.\n *\n * @internal\n * @see ./page.md\n"
            " * @see {@link ../docs/page.md | Page} — what the page settles\n"
            " * @param a the input that matters\n */\nexport function f(a) {}\n"
        )
        self.assertEqual(self.kinds(src), {("jsdoc", 2)})

    def test_pragma_and_license_are_skipped(self):
        src = (
            "/* Copyright 2026 Example Co. Licensed under MIT. */\n"
            "// eslint-disable-next-line\n/**\n" + lines(3) + "\n */\nimport a from 'a';\nconst b = 1;\n"
        )
        self.assertEqual(self.kinds(src), {("overview", 3)})

    def test_comment_markers_inside_strings_and_templates_are_code(self):
        src = "const s = '/* not a comment */';\nconst t = `//\n// still template\n`;\nconst r = /\\/\\//;\n"
        self.assertEqual(self.kinds(src), set())

    def test_python_docstrings(self):
        src = '"""\n' + lines(16, "") + '\n"""\nimport os\n\n\ndef f():\n    """' + lines(11, "") + '\n    """\n    return os\n'
        self.assertEqual(self.kinds(src, "m.py"), {("overview", 16), ("jsdoc", 11)})

    def test_python_shebang_is_not_the_overview(self):
        src = '#!/usr/bin/env python3\n"""\n' + lines(16, "") + '\n"""\nimport os\n'
        self.assertEqual(self.kinds(src, "m.py"), {("overview", 16)})

    def test_shipped_script_and_tests_pass_their_own_check(self):
        skill_dir = SCRIPT.parents[1]
        with contextlib.redirect_stdout(io.StringIO()), contextlib.redirect_stderr(io.StringIO()):
            code = cb.main([str(skill_dir / "scripts"), str(skill_dir / "tests"),
                            "--baseline", os.path.join(tempfile.gettempdir(), "none.json")])
        self.assertEqual(code, 0)

    def test_rust_inner_doc_is_overview(self):
        src = "//! " + "\n//! ".join(f"line {i}" for i in range(16)) + "\nuse std::fs;\n\n/// doc\npub fn f() {}\n"
        self.assertEqual(self.kinds(src, "m.rs"), {("overview", 16), ("jsdoc", 1)})

    def test_generated_files_are_skipped(self):
        self.assertEqual(self.kinds("// @generated by tool\n" + overview(40)), set())


class Baseline(unittest.TestCase):
    def setUp(self):
        self.dir = tempfile.TemporaryDirectory()
        self.root = self.dir.name
        self.baseline = os.path.join(self.root, "comment-budget.json")

    def tearDown(self):
        self.dir.cleanup()

    def write(self, name, src):
        with open(os.path.join(self.root, name), "w", encoding="utf-8") as fh:
            fh.write(src)

    def run_check(self, *extra):
        with contextlib.redirect_stdout(io.StringIO()), contextlib.redirect_stderr(io.StringIO()):
            return cb.main([self.root, "--baseline", self.baseline, *extra])

    def test_over_budget_fails_without_baseline(self):
        self.write("a.ts", overview(20))
        self.assertEqual(self.run_check(), 1)

    def test_within_budget_passes(self):
        self.write("a.ts", overview(15))
        self.assertEqual(self.run_check(), 0)

    def test_project_limit_override_in_baseline(self):
        self.write("a.ts", overview(20))
        with open(self.baseline, "w") as fh:
            json.dump({"limits": {"overview": 25}, "surfaces": {}}, fh)
        self.assertEqual(self.run_check(), 0)

    def test_write_baseline_refuses_new_surfaces_without_accept(self):
        self.write("a.ts", overview(20))
        self.assertEqual(self.run_check("--write-baseline"), 1)
        self.assertFalse(os.path.exists(self.baseline))
        self.assertEqual(self.run_check("--write-baseline", "--accept"), 0)
        self.assertEqual(self.run_check(), 0)

    def test_growth_beyond_baseline_fails_and_reason_allows_it(self):
        self.write("a.ts", overview(20))
        self.run_check("--write-baseline", "--accept")
        self.write("a.ts", overview(21))
        self.assertEqual(self.run_check(), 1)
        with open(self.baseline) as fh:
            data = json.load(fh)
        key = next(iter(data["surfaces"]))
        data["surfaces"][key]["reason"] = "one rule whose cases depend on each other"
        with open(self.baseline, "w") as fh:
            json.dump(data, fh)
        self.assertEqual(self.run_check(), 0)

    def test_shrinking_requires_ratchet_and_ratchet_only_lowers(self):
        self.write("a.ts", overview(20))
        self.run_check("--write-baseline", "--accept")
        self.write("a.ts", overview(18))
        self.assertEqual(self.run_check(), 1)  # stale: baseline must come down
        self.assertEqual(self.run_check("--write-baseline"), 0)  # lowering needs no --accept
        with open(self.baseline) as fh:
            data = json.load(fh)
        self.assertEqual(next(iter(data["surfaces"].values()))["lines"], 18)
        self.write("a.ts", overview(15))
        self.assertEqual(self.run_check(), 1)  # entry now stale
        self.assertEqual(self.run_check("--write-baseline"), 0)
        with open(self.baseline) as fh:
            self.assertEqual(json.load(fh)["surfaces"], {})

    def test_key_survives_line_shifts(self):
        self.write("a.ts", "const x = 1;\n/**\n" + lines(11) + "\n */\nexport function f() {}\n")
        self.run_check("--write-baseline", "--accept")
        self.write("a.ts", "const x = 1;\nconst y = 2;\n\n/**\n" + lines(11) + "\n */\nexport function f() {}\n")
        self.assertEqual(self.run_check(), 0)


if __name__ == "__main__":
    unittest.main()
